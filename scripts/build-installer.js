// scripts/build-installer.js
// ============================================================================
// WoodTek ERP - Windows installer builder (Inno Setup)
// ----------------------------------------------------------------------------
// Wraps the WORKING portable FOLDER (dist/WoodTekERP-portable) into a real
// Windows installer (.exe):
//   - Welcome page
//   - License agreement
//   - Install path picker (default: C:\Program Files\WoodTekERP)
//   - Desktop shortcut (to Start-WoodTek.bat)
//   - Start Menu entry
//   - Finish page with "Launch WoodTek ERP"
//
// Requires Inno Setup 6 installed on the build machine:
//   https://jrsoftware.org/isdl.php
//
// Usage (on Windows):
//   npm run build               # Next.js production build
//   node scripts/build-portable-folder.js   # portable folder
//   npm run build:installer     # dist/WoodTekERP-Setup-1.0.0.exe
// ============================================================================

const { execSync } = require("node:child_process");
const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.resolve(__dirname, "..");
const DIST = path.join(ROOT, "dist");
const ISS_FILE = path.join(DIST, "woodtek-erp.iss");
const PORTABLE_DIR = path.join(DIST, "WoodTekERP-portable");
const OUTPUT_SETUP = path.join(DIST, "WoodTekERP-Setup-1.0.0.exe");

const APP_NAME = "WoodTek ERP";
const APP_VERSION = "1.0.0";
const APP_PUBLISHER = "WoodTek";
const APP_EXE_BASE = "WoodTekERP"; // base name for the installed launcher bat
const APP_DESCRIPTION = "WoodTek ERP - Furniture Service Center management";

function log(msg) {
  console.log(`\n\x1b[36m[build-installer]\x1b[0m ${msg}`);
}

function run(cmd, opts = {}) {
  log(`> ${cmd}`);
  execSync(cmd, { stdio: "inherit", ...opts });
}

function findInnoSetup() {
  const candidates = [
    "C:\\Program Files (x86)\\Inno Setup 6\\ISCC.exe",
    "C:\\Program Files\\Inno Setup 6\\ISCC.exe",
    "C:\\Program Files (x86)\\Inno Setup 5\\ISCC.exe",
    "C:\\Program Files\\Inno Setup 5\\ISCC.exe",
  ];
  for (const c of candidates) {
    if (fs.existsSync(c)) return c;
  }
  return null;
}

