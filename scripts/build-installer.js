// scripts/build-installer.js
// ============================================================================
// WoodTek ERP - Windows installer builder (Inno Setup)
// ----------------------------------------------------------------------------
// Generates a real Windows installer (.exe) with:
//   - Welcome page
//   - License agreement
//   - Install path picker
//   - Desktop shortcut
//   - Start Menu entry
//   - Finish page
//
// This requires Inno Setup to be installed on the build machine.
// Download: https://jrsoftware.org/isinfo.php
//
// Usage (on Windows):
//   npm install
//   npm run build              # first build the Next.js app
//   npm run build:portable     # build the portable .exe (optional)
//   npm run build:installer    # produces dist/WoodTekERP-Setup.exe
// ============================================================================

const { execSync } = require("node:child_process");
const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.resolve(__dirname, "..");
const DIST = path.join(ROOT, "dist");
const ISS_FILE = path.join(DIST, "woodtek-erp.iss");
const PORTABLE_EXE = path.join(DIST, "WoodTekERP-portable.exe");
const OUTPUT_SETUP = path.join(DIST, "WoodTekERP-Setup.exe");

const APP_NAME = "WoodTek ERP";
const APP_VERSION = "1.0.0";
const APP_PUBLISHER = "WoodTek";
const APP_EXE_BASE = "WoodTekERP"; // base name for the installed .exe
const APP_DESCRIPTION = "WoodTek ERP - Furniture Service Center management";

function log(msg) {
  console.log(`\n\x1b[36m[build-installer]\x1b[0m ${msg}`);
}

function run(cmd, opts = {}) {
  log(`> ${cmd}`);
  execSync(cmd, { stdio: "inherit", ...opts });
}

function findInnoSetup() {
  const candidates = [
    "C:\\Program Files (x86)\\Inno Setup 6\\ISCC.exe",
    "C:\\Program Files\\Inno Setup 6\\ISCC.exe",
    "C:\\Program Files (x86)\\Inno Setup 5\\ISCC.exe",
    "C:\\Program Files\\Inno Setup 5\\ISCC.exe",
  ];
  for (const c of candidates) {
    if (fs.existsSync(c)) return c;
  }
  return null;
}

