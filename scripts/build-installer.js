function ensurePortableFolderExists() {
  if (!fs.existsSync(path.join(PORTABLE_DIR, "Start-WoodTek.bat"))) {
    throw new Error(
      `Portable folder not found at ${PORTABLE_DIR} (missing Start-WoodTek.bat).\n` +
      `Run "node scripts/build-portable-folder.js" first.`,
    );
  }
}

async function main() {
  log("=== WoodTek ERP installer build ===\n");

  // 1. Pre-flight checks
  log("Step 1/4: Pre-flight checks...");
  ensurePortableFolderExists();
  if (!fs.existsSync(path.join(ROOT, "LICENSE.txt"))) generateLicense();
  if (!fs.existsSync(path.join(ROOT, "README-install.md"))) generateInstallReadme();
  if (!fs.existsSync(path.join(ROOT, "assets"))) {
    fs.mkdirSync(path.join(ROOT, "assets"), { recursive: true });
    log("Created assets/ folder. Add woodtek-icon.ico there for the installer icon.");
  }

  // 2. Generate the .iss file
  log("Step 2/4: Generating Inno Setup script...");
  fs.mkdirSync(DIST, { recursive: true });
  generateIssFile();

  // 3. Find ISCC.exe
  log("Step 3/4: Locating Inno Setup compiler...");
  const iscc = findInnoSetup();
  if (!iscc) {
    log(`\nInno Setup was not found in the standard install locations.`);
    log(`Download and install it from: https://jrsoftware.org/isdl.php`);
    log(`After install, re-run: npm run build:installer\n`);
    log(`Alternatively, you can manually compile the generated .iss file:`);
    log(`  ${ISS_FILE}`);
    return;
  }

  // 4. Compile
  log(`Step 4/4: Compiling installer (this takes 1-2 minutes)...`);
  log(`ISCC: ${iscc}`);
  run(`"${iscc}" "${ISS_FILE}"`, { cwd: DIST });

  if (fs.existsSync(OUTPUT_SETUP)) {
    const sizeMB = (fs.statSync(OUTPUT_SETUP).size / 1024 / 1024).toFixed(1);
    log(`\n=== Build complete ===`);
    log(`Output: ${OUTPUT_SETUP}`);
    log(`Size:   ${sizeMB} MB`);
    log(`\nDistribute this single file. Users double-click to install.`);
  } else {
    log(`\n=== Build finished, but output file not found at:`);
    log(`${OUTPUT_SETUP}`);
    log(`Check the .iss file output above for the actual filename.`);
  }
}

main().catch((err) => {
  console.error("\n\x1b[31m[build-installer] FAILED:\x1b[0m", err.message);
  process.exit(1);
});
